CREATE TABLE goals (
    id uuid PRIMARY KEY,
    code varchar(60) NOT NULL,
    name varchar(100) NOT NULL,
    description varchar(500),
    created_at timestamp NOT NULL
);

CREATE UNIQUE INDEX goals_code_lower_idx ON goals (lower(code));
CREATE UNIQUE INDEX goals_name_lower_idx ON goals (lower(name));

